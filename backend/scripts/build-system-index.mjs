// Regenerates src/data/systemIndex.ts: for each state, the larger water systems
// with the city they are registered in, built from waterviolations.org's per-state
// CSVs (EPA SDWIS, public domain). Downloads one state at a time and discards it.
// Usage: node scripts/build-system-index.mjs [--data-end YYYY-MM-DD]
// Each system also gets a compact violation PROFILE (health-based violations in the
// last 5 years with class + open flag, and paperwork counts) so scoring needs no live call.
// Note: the CSVs list violations only, so a system with no violations ever is absent.
import { writeFileSync } from "node:fs";
import { classifyViolation } from "./violation-classes.mjs";

const argEnd = process.argv.indexOf("--data-end");
const DATA_END = argEnd > -1 ? process.argv[argEnd + 1] : "2025-12-31"; // keep in sync with DATA_THROUGH_ISO in the adapter
const HISTORY_YEARS = 5;
const PAPERWORK_WINDOW_MONTHS = 12;
const minusMonths = (iso, m) => { const d = new Date(iso + "T00:00:00Z"); d.setUTCMonth(d.getUTCMonth() - m); return d.toISOString().slice(0, 10); };
const HISTORY_START = minusMonths(DATA_END, HISTORY_YEARS * 12);
const PAPERWORK_START = minusMonths(DATA_END, PAPERWORK_WINDOW_MONTHS);

const MIN_POPULATION = 1000;
const STATES = "ak al ar az ca co ct dc de fl ga hi ia id il in ks ky la ma md me mi mn mo ms mt nc nd ne nh nj nm nv ny oh ok or pa ri sc sd tn tx ut va vt wa wi wv wy".split(" ");

function* parseCsv(text) {
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false; }
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n") { row.push(field); field = ""; yield row; row = []; }
    else if (ch !== "\r") field += ch;
  }
  if (field || row.length) { row.push(field); yield row; }
}

const index = {};
for (const st of STATES) {
  const res = await fetch(`https://waterviolations.org/data/${st}.csv`, { redirect: "follow" });
  if (!res.ok) { console.warn(`skip ${st}: HTTP ${res.status}`); continue; }
  const rows = parseCsv(await res.text());
  const header = rows.next().value;
  const col = Object.fromEntries(header.map((h, i) => [h, i]));
  const systems = new Map();
  for (const r of rows) {
    if (r.length < header.length) continue;
    const pwsid = r[col.pwsid];
    if (!pwsid.startsWith(st.toUpperCase())) continue; // city is in this state but system belongs to another
    const pop = Number(r[col.population]) || 0;
    if (pop < MIN_POPULATION) continue;
    let s = systems.get(pwsid);
    if (!s) systems.set(pwsid, (s = { pwsid, name: r[col.system_name], city: r[col.city], pop, health: [], openPaperwork: 0, paperwork12m: 0 }));
    const begin = r[col.begin_date].slice(0, 10);
    const open = r[col.compliance_status] === "O";
    if (r[col.health_based] === "true") {
      if (open || begin >= HISTORY_START) {
        const cls = classifyViolation({ contaminantCode: r[col.contaminant_code], violationName: r[col.violation_name] });
        s.health.push(`${begin || "?"}.${cls}.${open ? "o" : "c"}`);
      }
    } else {
      if (open) s.openPaperwork++;
      if (begin >= PAPERWORK_START && begin <= DATA_END) s.paperwork12m++;
    }
  }
  // line: pwsid|name|city|pop|health violations "date.class.open;..."|open paperwork|paperwork in last 12 months
  index[st.toUpperCase()] = [...systems.values()]
    .map((s) => [s.pwsid, s.name, s.city, s.pop, s.health.join(";"), s.openPaperwork, s.paperwork12m]
      .map((v) => String(v).replace(/[|\n]/g, " ")).join("|")).join("\n");
  console.log(st, systems.size);
  await new Promise((r) => setTimeout(r, 400)); // be polite
}
writeFileSync(
  new URL("../src/data/systemIndex.ts", import.meta.url),
  `// GENERATED by scripts/build-system-index.mjs, do not edit.\n// Source: EPA SDWIS via waterviolations.org per-state CSVs (public domain).\n// Per state, one line per system: "pwsid|name|registered city|population|health violations|open paperwork|paperwork last 12 mo".\n// Health violations are "date.class.open" joined by ";" (class b/n/t urgent, g long-term; open o/c).\nexport const INDEX_DATA_END = ${JSON.stringify(DATA_END)};\nexport const SYSTEM_INDEX: Record<string, string> = ${JSON.stringify(index)};\n`,
);
