// Regenerates src/data/zipPlaces.ts from GeoNames postal codes.
// Usage: node scripts/build-zip-places.mjs path/to/US.txt
// Source: https://download.geonames.org/export/zip/US.zip  (CC BY 4.0, attribution required)
import { readFileSync, writeFileSync } from "node:fs";

const lines = [];
for (const row of readFileSync(process.argv[2], "utf8").split("\n")) {
  const c = row.split("\t");
  if (c.length < 11 || !/^\d{5}$/.test(c[1])) continue;
  const [zip, city, st, lat, lon] = [c[1], c[2], c[4], Number(c[9]), Number(c[10])];
  if (!st || !city || Number.isNaN(lat) || Number.isNaN(lon)) continue;
  lines.push(`${zip}|${lat.toFixed(4)}|${lon.toFixed(4)}|${st}|${city.replace(/\|/g, " ")}`);
}
lines.sort(); // fixed-width ZIP prefix => lexicographic == numeric; enables binary search
writeFileSync(
  new URL("../src/data/zipPlaces.ts", import.meta.url),
  `// GENERATED by scripts/build-zip-places.mjs, do not edit.\n// Data: GeoNames postal codes, CC BY 4.0 (https://www.geonames.org/).\n// One line per ZIP, sorted: "zip|lat|lon|state|city".\nexport const ZIP_PLACES = ${JSON.stringify(lines.join("\n"))};\n`,
);
console.log(`wrote ${lines.length} ZIPs`);
